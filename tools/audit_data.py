#!/usr/bin/env python3
"""Audit the shared entity contract; write a reproducible review queue without changing data."""
import argparse
import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TYPES = {'building', 'address', 'programme', 'property_asset'}
METHODS = {'footprint_centroid', 'footprint_point', 'address_point', 'street_point', 'programme_point', 'asset_point'}

def audit(root=ROOT):
    report = {'methodology_version': 1, 'cities': {}, 'errors': []}
    seen_uids = set()
    for entry in json.loads((root / 'site.json').read_text())['cities']:
        city = entry['id']
        cfg = json.loads((root / 'cities' / city / 'config.json').read_text())
        raw = json.loads((root / 'cities' / city / cfg.get('data', 'addresses.json')).read_text())
        rows = raw if isinstance(raw, list) else [f['properties'] | {'lon': f['geometry']['coordinates'][0], 'lat': f['geometry']['coordinates'][1]} for f in raw['features']]
        coords, addresses, refs = (collections.defaultdict(list) for _ in range(3))
        errors = report['errors']
        sources = {s['key'] for s in cfg.get('sources', [])}
        ids = set()
        for row in rows:
            uid = row.get('record_uid')
            prefix = f'{city}:{row.get("id", "missing-id")}'
            def fail(message): errors.append(f'{prefix}: {message}')
            if not isinstance(row.get('id'), int) or row['id'] in ids: fail('missing or duplicate numeric share-link ID')
            ids.add(row.get('id'))
            if uid != prefix or uid in seen_uids: fail('invalid or duplicate record_uid')
            seen_uids.add(uid)
            if row.get('methodology_version') != 1: fail('missing methodology version')
            if row.get('entity_type') not in TYPES: fail('unknown entity type')
            if row.get('coordinate_method') not in METHODS: fail('unknown coordinate method')
            if row.get('source') not in sources: fail('source is not linked in city config')
            if 'source_as_of' not in row: fail('source_as_of must be explicit; null means unknown')
            if row.get('tenure_scope') not in {'unknown', 'all_social_reported', 'mixed_reported'}: fail('unknown tenure scope')
            status = row.get('verification_status')
            if status not in {'source_verified', 'legacy_review_required'}: fail('unknown verification status')
            if status == 'source_verified':
                for field in ['building_ref', 'source_record_id', 'reviewed_on', 'verification_note', 'coordinate_source']:
                    if not row.get(field): fail(f'verified building requires {field}')
                if row.get('entity_type') != 'building': fail('verified entity must be a building')
                if row.get('coordinate_method') not in {'footprint_centroid', 'footprint_point', 'address_point'}: fail('building needs footprint or matched entrance position')
            coords[(row['lat'], row['lon'])].append(uid)
            addresses[' '.join(row['address'].casefold().split())].append(uid)
            if row.get('building_ref'): refs[row['building_ref']].append(uid)
        aliases = set()
        for row in rows:
            for alias in row.get('legacy_ids', []):
                if not isinstance(alias, int) or alias in ids or alias in aliases:
                    errors.append(f'{city}: duplicate or invalid retired ID {alias}')
                aliases.add(alias)
        for ref, group in refs.items():
            if len(group) > 1: errors.append(f'{city}: duplicate building identity {ref}: {group}')
        report['cities'][city] = {
            'records': len(rows),
            'verified_buildings': sum(r.get('verification_status') == 'source_verified' for r in rows),
            'legacy_review_required': sum(r.get('verification_status') == 'legacy_review_required' for r in rows),
            'entity_types': dict(sorted(collections.Counter(r.get('entity_type') for r in rows).items())),
            'coordinate_methods': dict(sorted(collections.Counter(r.get('coordinate_method') for r in rows).items())),
            'coincident_coordinate_groups': [v for v in coords.values() if len(v) > 1],
            'repeated_address_groups': [v for v in addresses.values() if len(v) > 1],
            'street_level_records': [r['record_uid'] for r in rows if r.get('coordinate_method') == 'street_point'],
        }
    return report

def markdown(report):
    lines = ['# Entity audit — methodology v1', '', 'Generated by `python3 tools/audit_data.py --write`. This is a structural audit of every published record, not a claim that every source or building has been checked manually.', '', 'Repeated coordinates/addresses are review candidates, not automatic duplicates. Counts are records unless explicitly labelled buildings. Zero rows means no published evidence yet, not no social housing.', '', '| City | Records | Source-verified buildings | Legacy review | Coincident coordinate groups | Street-only points |', '|---|---:|---:|---:|---:|---:|']
    for city, v in report['cities'].items():
        lines.append(f'| {city} | {v["records"]} | {v["verified_buildings"]} | {v["legacy_review_required"]} | {len(v["coincident_coordinate_groups"])} | {len(v["street_level_records"])} |')
    lines += ['', '## Review order', '', '1. Resolve street-only positions; withhold new street-only matches.', '2. Resolve Paris programme-to-building relationships before counting buildings or summing homes.', '3. Match Rome property assets and civic-address datasets to building identities; a property can be one flat or several buildings.', '4. Check repeated addresses and coincident coordinates using source IDs and footprints; never jitter coordinates or merge on distance alone.', '5. Expand the five cities initially lacking mapped data, starting with Turin’s documented building. Research every district and provider, including negative search results.', '', 'The machine-readable `entity-audit.json` lists stable record IDs for collision and street-position review. Legacy records remain visible and explicitly labelled during migration. Only source-verified buildings may be added as new mapped records under v1; unresolved candidates belong in source research logs.', '', f'Contract errors: {len(report["errors"])}', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--base', help='Git revision against which to enforce verified-building-only additions')
    args = parser.parse_args()
    result = audit()
    if args.base:
        import subprocess
        for city in result['cities']:
            path = f'cities/{city}/addresses.json'
            previous = subprocess.run(['git', 'show', f'{args.base}:{path}'], cwd=ROOT, capture_output=True, text=True)
            if previous.returncode and 'does not exist' not in previous.stderr and 'exists on disk, but not in' not in previous.stderr:
                raise SystemExit(previous.stderr)
            old = json.loads(previous.stdout) if previous.returncode == 0 else []
            old_ids = {r.get('id', i) for i, r in enumerate(old)}
            for row in json.loads((ROOT/path).read_text()):
                if row.get('id') not in old_ids and (row.get('entity_type') != 'building' or row.get('verification_status') != 'source_verified'):
                    result['errors'].append(f'{city}:{row.get("id")}: new records must be verified buildings')
    if args.write:
        (ROOT/'docs').mkdir(exist_ok=True)
        (ROOT/'docs/entity-audit.json').write_text(json.dumps(result, ensure_ascii=False, indent=2)+'\n')
        (ROOT/'docs/entity-audit.md').write_text(markdown(result))
    print(markdown(result))
    for error in result['errors']: print(error)
    raise SystemExit(bool(result['errors']))
